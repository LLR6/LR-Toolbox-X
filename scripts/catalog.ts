import { writeFile, mkdir, readFile } from "node:fs/promises";
import { metadata, actions, execute } from "../packages/registry/src/index.ts";
await mkdir("docs", { recursive: true });
const content =
  "# Implemented portable actions\n\nGenerated from executable registry. Native actions are listed separately.\n\n| ID | 名称 | Category | Platforms | Risk |\n|---|---|---|---|---|\n" +
  actions
    .map(
      (a) =>
        `| ${a.id} | ${a.name} | ${a.category} | ${a.platforms.join(", ")} | ${a.risk_level} |`,
    )
    .join("\n") +
  "\n";
await writeFile("docs/actions.md", content);
await writeFile(
  "apps/web/public/action-catalog.json",
  JSON.stringify(metadata(), null, 2),
);
const androidIds: string[] = JSON.parse(
  await readFile("apps/android/native-actions.json", "utf8"),
);
if (new Set(androidIds).size !== androidIds.length)
  throw Error("Duplicate Android capability ID");
const androidActions = androidIds.map((id) => {
  const action = actions.find((a) => a.id === id);
  if (
    !action ||
    Object.keys(action.input_schema.properties ?? {}).join() !== "text" ||
    action.output_schema.type !== "string"
  )
    throw Error("Android text contract missing: " + id);
  return action;
});
await writeFile(
  "apps/android/app/src/main/assets/action-catalog.json",
  JSON.stringify(
    metadata()
      .filter((a) => androidIds.includes(a.id))
      .map((a) => ({ ...a, platforms: ["android"] })),
    null,
    2,
  ),
);
const kotlinString = (value: string) =>
  JSON.stringify(value).replaceAll("$", "\\$");
await writeFile(
  "apps/android/app/src/main/java/io/github/llr6/lrx/NativeActionIds.kt",
  `// Generated by npm run catalog from apps/android/native-actions.json.
package io.github.llr6.lrx
object NativeActionIds {
    val values: Set<String> = setOf(
${androidIds.map((id) => "        " + kotlinString(id)).join(",\n")}
    )
}
`,
);
const fixtures = await Promise.all(
  androidActions.map(async (a) => [
    a.id,
    a.example.text as string,
    (await execute(a.id, a.example)) as string,
  ]),
);
await writeFile(
  "apps/android/app/src/test/java/io/github/llr6/lrx/PortableConformanceTest.kt",
  `// Generated against the executable portable registry by npm run catalog.
package io.github.llr6.lrx
import org.junit.Assert.assertEquals
import org.junit.Test
class PortableConformanceTest {
    @Test fun sharedExamplesMatchNativeHandlers() {
        val fixtures = listOf(
${fixtures.map((f) => "            Triple(" + f.map(kotlinString).join(", ") + ")").join(",\n")}
        )
        assertEquals(Codec.ids, fixtures.map { it.first }.toSet())
        for ((id, input, expected) in fixtures) assertEquals(id, expected, Codec.run(id, input))
    }
}
`,
);
console.log(
  JSON.stringify(
    {
      totalPortable: actions.length,
      nativeAndroid: androidIds.length,
      portableRuntimes: Object.fromEntries(
        ["web", "windows", "linux", "macos", "cli", "android"].map((p) => [
          p,
          actions.filter((a) => a.platforms.includes(p as "web")).length,
        ]),
      ),
    },
    null,
    2,
  ),
);
